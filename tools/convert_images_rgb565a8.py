#!/usr/bin/env python3
"""Convert LVGL 9 ARGB8888 C image arrays to RGB565A8 (3 bytes/pixel instead of 4).

    python convert_images_rgb565a8.py IN_argb8888.h OUT.h

ARGB8888 in memory is B, G, R, A per pixel. RGB565A8 is the whole RGB565 plane
(little-endian, stride = w*2) followed by the whole 8-bit alpha plane.
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
arrays = {m.group(1): bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", m.group(2)))
          for m in re.finditer(r"uint8_t\s+(\w+)_map\[\]\s*=\s*\{(.*?)\};", src, re.S)}
dims = {m.group(1): (int(m.group(2)), int(m.group(3)))
        for m in re.finditer(r"lv_image_dsc_t\s+(\w+)\s*=\s*\{.*?\.w\s*=\s*(\d+),\s*\.h\s*=\s*(\d+)", src, re.S)}

out = ["/* Weather icons, LVGL 9 RGB565A8. Generated by tools/convert_images_rgb565a8.py",
       " * from tools/weather_images_argb8888.h - do not edit. */",
       "#pragma once", '#include "lvgl.h"', ""]
for name, (w, h) in dims.items():
    px = arrays[name]
    assert len(px) == w * h * 4, (name, len(px), w, h)
    rgb, alpha = bytearray(), bytearray()
    for i in range(0, len(px), 4):
        b, g, r, a = px[i:i + 4]
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        rgb += bytes((v & 0xFF, v >> 8))
        alpha.append(a)
    data = rgb + alpha
    out.append(f"static const LV_ATTRIBUTE_MEM_ALIGN uint8_t {name}_map[] = {{")
    for j in range(0, len(data), 24):
        out.append("    " + ",".join(f"0x{x:02x}" for x in data[j:j + 24]) + ",")
    out.append("};")
    out.append(f"const lv_image_dsc_t {name} = {{")
    out.append(f"    .header = {{.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .flags = 0,")
    out.append(f"               .w = {w}, .h = {h}, .stride = {w * 2}, .reserved_2 = 0}},")
    out.append(f"    .data_size = sizeof({name}_map), .data = {name}_map, .reserved = NULL,")
    out.append("};\n")
    print(f"{name}: {w}x{h}  {len(px)} -> {len(data)} bytes")
open(sys.argv[2], "w", encoding="utf-8").write("\n".join(out) + "\n")
